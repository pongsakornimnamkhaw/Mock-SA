// ─── Usage Logs ─────────────────────────────────────────────────────────────
const usageLogs = (promotionId: string, count: number): PromotionUsageLog[] => {
  const names = ['สมชาย ไอดี', 'มานี มีนาม', 'วิชัย สุขดี', 'รัตนา แก้วใส', 'ประยุทธ์ ดาวดี', 'สาวิตรี รุ่งเรือง', 'นิติ พรมมา', 'กมล วงษ์'];
  const zones = ['ZONE: A1', 'ZONE: VIP', 'ZONE: B2', 'ZONE: A2', 'ZONE: B1', 'ZONE: C1'];
  return Array.from({ length: count }, (_, i) => ({
    usage_log_id: `ul-${promotionId}-${i}`,
    used_at: `2026-08-${String(17 - (i % 10)).padStart(2, '0')}T14:${String(20 + (i % 40)).padStart(2, '0')}:00`,
    user_name: names[i % names.length],
    user_id: String(800 + i),
    order_id: `ORD-${9900 - i * 13}`,
    purchased_zone: zones[i % zones.length],
    final_amount: [2400, 4800, 1200, 3600, 960][i % 5],
    promotion_id: promotionId,
  }));
};

